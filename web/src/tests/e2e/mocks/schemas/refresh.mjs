// Writes SDL snapshots of the subgraph query APIs for the e2e subgraph mock.
// subgraph/*/schema.graphql is the entity schema; it lacks the filters, orderBy and _meta The Graph generates.
// Run from web/: `yarn e2e:schemas` (devnet endpoints from .env.devnet.public).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { buildClientSchema, getIntrospectionQuery, lexicographicSortSchema, printSchema } from "graphql";

const here = dirname(fileURLToPath(import.meta.url));

const endpoints = {
  core: process.env.REACT_APP_CORE_SUBGRAPH,
  drt: process.env.REACT_APP_DRT_ARBSEPOLIA_SUBGRAPH,
};

for (const [name, url] of Object.entries(endpoints)) {
  if (!url) throw new Error(`No URL for the ${name} subgraph; run through scripts/runEnv.sh devnet`);
  const res = await fetch(url, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ query: getIntrospectionQuery() }),
  });
  const { data, errors } = await res.json();
  if (errors?.length) throw new Error(`${name}: ${JSON.stringify(errors)}`);
  const sdl = printSchema(lexicographicSortSchema(buildClientSchema(data)));
  const file = join(here, `${name}.graphql`);
  writeFileSync(file, `# Generated by refresh.mjs (yarn e2e:schemas). Do not edit.\n${sdl}\n`);
  // Keep the snapshot stable under the repo's format check.
  execFileSync("yarn", ["run", "-T", "prettier", "--write", "--log-level", "warn", file], { stdio: "inherit" });
  console.log(`wrote ${file}`);
}
