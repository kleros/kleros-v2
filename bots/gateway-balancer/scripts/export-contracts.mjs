// Exports the gateway ABIs and the bytecode the Anvil tests deploy from the Hardhat artifacts of `contracts/`.
// Run `yarn workspace @kleros/kleros-v2-contracts build` first, then `yarn workspace @kleros/gateway-balancer-bot
// export-contracts`. Writes `src/contracts/abi.ts` and `src/contracts/bytecode.json`; never edit them by hand.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import { hashContractSources } from "./contractSources.mjs";

const botDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contractsDir = path.resolve(botDir, "../../contracts");
const outDir = path.join(botDir, "src/contracts");

/** [export name, artifact path under contracts/artifacts]; each gets an ABI and the bytecode the Anvil tests deploy. */
const CONTRACTS = [
  ["foreignGateway", "src/gateway/ForeignGateway.sol/ForeignGateway.json"],
  ["homeGateway", "src/gateway/HomeGateway.sol/HomeGateway.json"],
  ["uupsProxy", "src/proxy/UUPSProxy.sol/UUPSProxy.json"],
  ["testErc20", "src/token/TestERC20.sol/TestERC20.json"],
];

const sourceHash = hashContractSources(contractsDir);
let abiModule =
  "// Generated by scripts/export-contracts.mjs from the Hardhat artifacts of contracts/. Do not edit.\n\n" +
  `/** SHA-256 over the Solidity sources the artifacts were compiled from; see scripts/contractSources.mjs. */\n` +
  `export const CONTRACT_SOURCES_HASH = "${sourceHash}";\n`;
const bytecode = { sourceHash };

for (const [name, artifactPath] of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(path.join(contractsDir, "artifacts", artifactPath), "utf8"));
  abiModule += `\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  bytecode[name] = artifact.bytecode;
}

const abiPath = path.join(outDir, "abi.ts");
const prettierOptions = { ...(await prettier.resolveConfig(abiPath)), filepath: abiPath };
writeFileSync(abiPath, await prettier.format(abiModule, prettierOptions));
writeFileSync(path.join(outDir, "bytecode.json"), JSON.stringify(bytecode, null, 2) + "\n");
console.log(`exported ${CONTRACTS.length} contracts, sources ${sourceHash}`);
